#!/usr/bin/env node
/*
 * make-test-texts — write realistic Sinhala test text into test-texts/generated/.
 *
 *   node tools/test-generator/make-test-texts.js [--out DIR] [--seed N]
 *
 * Uses the same engine as the page (textgen.js) and the data bundle built by
 * test-texts/corpus-build, so the text matches what the page produces for the same
 * set and seed.
 *
 *   stages.md              text for a font at design stage 1..10 (cumulative)
 *   levels.md              text for a font at glyphset level Kernel, Core
 *   targeted-*.md          real sentences densest in rakaransaya, yansaya, repaya,
 *                          other conjuncts, each vowel sign, and the rare letters
 *   README.md              what is here, and per-section statistics
 *
 * Output is deterministic for a given seed and data bundle. Invented words are
 * not marked in the files; README.md says how much of each section is invented.
 */
"use strict";

const fs = require("fs");
const path = require("path");

const G = require("./graphemes.js");
const TG = require("./textgen.js");
const Presets = require("./presets.js");

const REPO = path.resolve(__dirname, "../..");
const opt = {
  out: path.join(REPO, "test-texts/generated"),
  data: path.join(__dirname, "data"),
  stages: path.join(REPO, "sinhala-design-stages/stages.json"),
  seed: 1,
};
for (let i = 2; i < process.argv.length; i++) {
  const a = process.argv[i];
  if (a === "-h" || a === "--help") { console.log(fs.readFileSync(__filename, "utf8").split("*/")[0]); process.exit(0); }
  const m = /^--(\w+)$/.exec(a);
  if (!m || !(m[1] in opt)) { console.error("unknown option: " + a); process.exit(2); }
  const v = process.argv[++i];
  opt[m[1]] = typeof opt[m[1]] === "number" ? Number(v) : path.resolve(v);
}

const short = (g) => G.nameOf(g).replace(/-sinh$/, "");
const text = (res) => res.sentences.map((s) => s.map((p) => p.t).join("")).join(" ");
const lines = (res) => res.sentences.map((s) => s.map((p) => p.t).join(""));

const frontmatter = (title, description) => [
  "---",
  "title: " + title,
  "description: " + description,
  "language: sin",
  "script: sin",
  "writing_systems:",
  "credits: Generated by tools/test-generator/make-test-texts.js from the UCSC Language Technology Research Laboratory (LTRL) Sinhala corpora",
  "copyright: Language Technology Research Laboratory, University of Colombo School of Computing",
  "license: LGPL-LR",
  "year: 2026",
  "url: https://github.com/mooniak/sinhala-font-tools",
  "",
  "layout: default.html",
  "collection: tests",
  "---",
  "",
].join("\n");

const stats = [];   // for README.md

// ---- per-set sections (stages, levels) -------------------------------------

async function presetSection(eng, file, head, items, seed) {
  const set = G.parseList(items.join(" ")).graphemes;
  const s = eng.session(set, { fromParts: true });
  const tpl = await s.templates({ seed, count: 6 });
  const run = s.chain({ seed, words: 60 });
  const inv = s.pseudo({ seed, count: 30 });
  await s.loadSentences();
  const real = s.pool.length >= 200 ? s.sentences({ seed, count: 6 }) : null;

  const rows = [
    ["templates", tpl, text(tpl)],
    ["chain", run, text(run)],
    ["real sentences", real, real && text(real)],
    ["invented words", inv, inv.sentences.map((x) => x[0].t).join(" ")],
  ];
  rows.forEach(([kind, r]) => {
    if (r) stats.push({ file, section: head, kind, words: r.stats.words, inv: r.stats.inventedPct, shown: r.stats.shown, of: r.stats.graphemes });
  });

  return "## " + head + "\n\n" +
    "GLYPHS  : " + items.map((it) => short(G.parseList(it).graphemes[0] || it)).join(" ") + "\n\n" +
    "TEMPLATES : " + rows[0][2] + "\n\n" +
    "TEXT : " + rows[1][2] + "\n\n" +
    (real ? "SENTENCES : " + rows[2][2] + "\n\n" : "") +
    "INVENTED : " + rows[3][2] + "\n";
}

// ---- targeted collections --------------------------------------------------

function section(head, sents) { return sents.length ? "## " + head + "\n\n" + sents.join("\n") + "\n" : ""; }

const RARE = 6000;   // a letter is "rare" when it occurs in at most this many corpus sentences

async function main() {
  const eng = await TG.load(TG.dirReader(opt.data));
  const stagesJson = JSON.parse(fs.readFileSync(opt.stages, "utf8"));
  const presets = Presets.build(stagesJson);
  fs.mkdirSync(opt.out, { recursive: true });
  const written = [];
  const write = (name, body) => { fs.writeFileSync(path.join(opt.out, name), body); written.push([name, Buffer.byteLength(body)]); };

  // stages and levels
  let body = frontmatter("Sinhala test text by design stage",
    "Realistic Sinhala text using only the graphemes a font has by each design stage (cumulative)");
  for (const st of presets.stages) {
    console.error("stage " + st.n);
    body += (await presetSection(eng, "stages.md", "Stage " + st.n + " — " + st.name, st.items, opt.seed + st.n)) + "\n";
  }
  write("stages.md", body.replace(/\n+$/, "\n"));

  body = frontmatter("Sinhala test text by glyphset level",
    "Realistic Sinhala text using only the graphemes a font has at glyphset level Kernel and Core");
  for (const lv of presets.levels) {
    console.error("level " + lv.label);
    body += (await presetSection(eng, "levels.md", lv.label + " (level " + lv.n + ")", lv.items, opt.seed + 100 + lv.n)) + "\n";
  }
  write("levels.md", body.replace(/\n+$/, "\n"));

  // targeted collections run over every grapheme the bundle knows
  const all = eng.session(eng.index.graphemes);
  await all.loadSentences();
  const pick = (spec, count, o) => {
    const seen = new Set();
    return lines(all.targeted(spec, Object.assign({ count: count * 2, exclude: "lnh", seed: opt.seed }, o)))
      .filter((t) => !seen.has(t) && seen.add(t)).slice(0, count);
  };
  const collection = (file, title, description, sections) => {
    let b = frontmatter(title, description);
    sections.forEach(([head, sents]) => {
      b += section(head, sents) + "\n";
      stats.push({ file, section: head, kind: "real sentences", words: null, n: sents.length });
    });
    write(file, b.replace(/\n+$/, "\n"));
  };

  collection("targeted-rakar.md", "Sinhala sentences dense in rakaransaya", "Real sentences with the most rakaransaya (්‍ර)",
    [["rakaransaya", pick({ classes: ["rakar"] }, 40, { minHits: 3 })]]);
  collection("targeted-yansa.md", "Sinhala sentences dense in yansaya", "Real sentences with the most yansaya (්‍ය)",
    [["yansaya", pick({ classes: ["yansa"] }, 40, { minHits: 3 })]]);
  collection("targeted-repha.md", "Sinhala sentences dense in repaya", "Real sentences with the most repaya (ර්‍)",
    [["repaya", pick({ classes: ["repha"] }, 40, { minHits: 2 })]]);
  collection("targeted-conjuncts.md", "Sinhala sentences dense in conjuncts", "Real sentences with the most ZWJ conjuncts of any kind",
    [["conjuncts", pick({ classes: ["conjunct"] }, 40, { minHits: 4 })]]);

  const signs = ["ා", "ැ", "ෑ", "ි", "ී", "ු", "ූ", "ෘ", "ෙ", "ේ", "ෛ", "ො", "ෝ", "ෞ", "ෲ", "ෟ", "ං", "ඃ"];
  collection("targeted-signs.md", "Sinhala sentences dense in each vowel sign", "Real sentences with the most of each vowel sign and spacing mark",
    signs.map((sg) => [sg + " " + short(sg), pick({ signs: [sg] }, 4, { minHits: 3 })]));

  // bare letters found in at most RARE sentences of the corpus
  const rare = eng.index.graphemes.map((g, i) => ({ g, df: eng.index.df[i], d: G.decompose(g) }))
    .filter((x) => x.d.kind !== "M" && !x.d.sign && [...x.g].length === 1 && x.df <= RARE)
    .sort((a, b) => a.g.codePointAt(0) - b.g.codePointAt(0));
  collection("targeted-rare-letters.md", "Sinhala sentences with rare letters",
    "Real sentences for the letters found in at most " + RARE.toLocaleString("en") + " corpus sentences, three each (fewer where the corpus has fewer)",
    rare.map((x) => [x.g + " " + short(x.g) + " (" + x.df + " sentences in the corpus)", pick({ graphemes: [x.g] }, 3, { minHits: 1 })]));

  // README
  const pct = (x) => Math.round(x * 100) + "%";
  let readme = "# Generated test text\n\n" +
    "Written by [`tools/test-generator/make-test-texts.js`](../../tools/test-generator/make-test-texts.js) " +
    "(seed " + opt.seed + ") — **do not edit by hand**; rerun the script instead. Derived from the UCSC LTRL Sinhala " +
    "corpora under the LGPL-LR ([licence](../corpus-build/LICENSE-LGPL-LR.txt)).\n\n" +
    "These sit in a subfolder on purpose: files in `test-texts/` itself are picked up by the proof-PDF tool, " +
    "and these are copied to the two consumers only when you decide to.\n\n" +
    "| File | What it is |\n|---|---|\n" +
    "| `stages.md` | Per design stage 1–10 (cumulative): glyph list, template sentences, running text, real sentences (when enough exist), invented words |\n" +
    "| `levels.md` | The same for glyphset levels Kernel and Core |\n" +
    "| `targeted-*.md` | Real sentences densest in rakaransaya, yansaya, repaya, conjuncts, each vowel sign, and the rare letters (in at most " + RARE.toLocaleString("en") + " corpus sentences) |\n\n" +
    "In the stage and level files **TEMPLATES** are real news sentences with the words the font cannot yet show replaced by " +
    "invented words of the same shape; **TEXT** is running text from word-pair statistics; **SENTENCES** are verbatim real " +
    "sentences (only where a font has enough common graphemes to have any); **INVENTED** is a list of made-up words. " +
    "Invented words follow Sinhala word-shape rules but are not real words, so they are not marked in the files; the table " +
    "below says how much of each section is invented. Every listed grapheme appears at least once in TEMPLATES and in TEXT.\n\n" +
    "## Statistics\n\n| File | Section | Kind | Words | Invented | Graphemes shown |\n|---|---|---|---|---|---|\n";
  stats.filter((r) => r.words != null).forEach((r) => {
    readme += "| " + r.file + " | " + r.section + " | " + r.kind + " | " + r.words + " | " + pct(r.inv) + " | " + r.shown + " / " + r.of + " |\n";
  });
  readme += "\nTargeted collections hold real sentences only (nothing invented).\n";
  write("README.md", readme);

  console.log(written.map(([n, b]) => "  " + n.padEnd(26) + (b / 1024).toFixed(0).padStart(5) + " KB").join("\n"));
}

main().catch((e) => { console.error(e); process.exit(1); });
